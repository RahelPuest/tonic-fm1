def scale2x(rows):
    """EPX / Scale2x: a glyph (strings of # and .) at twice its size, the diagonals smoothed"""
    h, w = len(rows), len(rows[0])
    g = lambda x, y: rows[y][x] == "#" if 0 <= x < w and 0 <= y < h else False
    out = [["."] * (2 * w) for _ in range(2 * h)]
    for y in range(h):
        for x in range(w):
            p, a, b, c, d = g(x, y), g(x, y - 1), g(x + 1, y), g(x - 1, y), g(x, y + 1)
            e = [p] * 4
            if c == a and c != d and a != b: e[0] = a
            if a == b and a != c and b != d: e[1] = b
            if d == c and d != b and c != a: e[2] = c
            if b == d and b != a and d != c: e[3] = d
            for k, (dx, dy) in enumerate(((0, 0), (1, 0), (0, 1), (1, 1))):
                out[2 * y + dy][2 * x + dx] = "#" if e[k] else "."
    return ["".join(r) for r in out]


def hires(out):
    """the full-resolution fonts (240 x 240): S9, 5 x 9 (the 5 x 7 glyphs, rows 2 and 4 twice: thin strokes, for
    the small text); M14, 10 x 14 and M28, 20 x 28 (the 5 x 7 glyphs smoothed by Scale2x once and twice)"""
    out += ["", "/* full resolution: S9 5 x 9 (bit 4 = left), M14 10 x 14 (bit 9 = left), M28 20 x 28 (bit 19 = left) */",
            "static const uint8_t OF_S9[64][9] = {"]
    for c in range(32, 96):
        r = M.get(chr(c), M["?"])
        r9 = [r[0], r[1], r[2], r[2], r[3], r[4], r[4], r[5], r[6]]
        out.append("    {" + ", ".join(str(int(x.replace("#", "1").replace(".", "0"), 2)) for x in r9) + "},")
    out += ["};", "static const uint16_t OF_M14[64][14] = {"]
    for c in range(32, 96):
        r = scale2x(M.get(chr(c), M["?"]))
        out.append("    {" + ", ".join(str(int(x.replace("#", "1").replace(".", "0"), 2)) for x in r) + "},")
    out += ["};", "static const uint32_t OF_M28[64][28] = {"]
    for c in range(32, 96):
        r = scale2x(scale2x(M.get(chr(c), M["?"])))
        out.append("    {" + ", ".join(str(int(x.replace("#", "1").replace(".", "0"), 2)) + "u" for x in r) + "},")
    out.append("};")


def main():
    out = ["/* SPDX-License-Identifier: MPL-2.0 */",
           "/* generated by tools/gen_oled_font.py: TONIC's OLED pixel fonts, ASCII 32..95 (lower case drawn as upper) */",
           "#pragma once", "", "/* S: 3 x 5, one byte a row (bit 2 = left), 5 bytes a glyph */",
           "static const uint8_t OF_S[64][5] = {"]
    for c in range(32, 96):
        rows = S.get(chr(c), S["?"]).split()
        assert len(rows) == 5 and all(len(r) == 3 for r in rows), chr(c)
        out.append("    {" + ", ".join(str(int(r.replace("#", "1").replace(".", "0"), 2)) for r in rows) + "},"
                   + f" /* {c} */")
    out += ["};", "", "/* M: 5 x 7, one byte a row (bit 4 = left), 7 bytes a glyph */", "static const uint8_t OF_M[64][7] = {"]
    for c in range(32, 96):
        rows = M.get(chr(c), M["?"])
        assert len(rows) == 7 and all(len(r) == 5 for r in rows), chr(c)
        out.append("    {" + ", ".join(str(int(r.replace("#", "1").replace(".", "0"), 2)) for r in rows) + "},")
    out.append("};")
    hires(out)
    p = Path(__file__).resolve().parents[1] / "app" / "oled_font.h"
    p.write_text("\n".join(out) + "\n")
    print("->", p)


if __name__ == "__main__":
    main()
