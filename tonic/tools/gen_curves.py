"""Derive TONIC's parameter curves from the Digitone OS analysis (research/firmware/tables/*.csv, made by the
research tools from Elektron's public OS 1.44 image) and write tonic/core/curves.h: compact knot tables that the
engine interpolates (in the log domain where the curve is exponential). The firmware's own tables are not copied;
each curve here reproduces the measured one within the error printed by this script.

  tools/gen_curves.py [RESEARCH_TABLES_DIR]   (default: ../research/firmware/tables)
"""
import csv
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parents[1] / "research" / "firmware" / "tables"
OUT = HERE.parent / "core" / "curves.h"


def column(name, col, n=128):
    rows = list(csv.DictReader(open(SRC / name)))
    return [float(r[col]) for r in rows][:n]


def knots(v, step, exact_from, low=5):
    """knot indices: every index below `low`, every `step` up to exact_from, then every index (the hand-placed
    tops)"""
    idx = list(range(0, low)) + list(range(((low + step - 1) // step) * step, exact_from, step)) + \
        list(range(exact_from, len(v)))
    return idx


def interp(idx, kv, i, log):
    for j in range(len(idx) - 1):
        a, b = idx[j], idx[j + 1]
        if a <= i <= b:
            t = (i - a) / (b - a) if b > a else 0
            ka, kb = kv[j], kv[j + 1]
            if log and ka > 0 and kb > 0:
                return math.exp(math.log(ka) + (math.log(kb) - math.log(ka)) * t)
            return ka + (kb - ka) * t
    return kv[-1]


def cfloat(x):
    t = f"{x:.9g}"
    if "e" not in t and "." not in t:
        t += ".0"
    return t + "f"


def emit(name, v, step, exact_from, log, note, low=5):
    idx = knots(v, step, exact_from, low)
    kv = [v[i] for i in idx]
    err = max((abs(interp(idx, kv, i, log) - v[i]) / max(abs(v[i]), 1e-9) if v[i] else
               abs(interp(idx, kv, i, log))) for i in range(len(v)))
    print(f"{name}: {len(idx)} knots, max relative error {err:.4f}")
    s = [f"/* {note}; {len(idx)} knots, max relative error {err:.4f} against the measured table */",
         f"#define {name}_N {len(idx)}",
         f"static const uint8_t {name}_I[{name}_N] = {{{', '.join(str(i) for i in idx)}}};",
         f"static const float {name}_V[{name}_N] = {{{', '.join(cfloat(x) for x in kv)}}};",
         f"#define {name}_LOG {1 if log else 0}"]
    return "\n".join(s)


def main():
    parts = ["/* SPDX-License-Identifier: MPL-2.0 */", "/* generated by tools/gen_curves.py from the Digitone OS 1.44 analysis: do not edit */",
             "#pragma once", "#include <stdint.h>"]
    parts.append(emit("CV_DTUN_A", column("sec7_detune_A.csv", "ratio_offset"), 4, 116, True,
                      "DTUN 0..127 -> the ratio offset added to operator A"))
    parts.append(emit("CV_DTUN_B2", column("sec7_detune_B2.csv", "ratio_offset"), 4, 116, True,
                      "DTUN 0..127 -> the ratio offset added to operator B2"))
    lvl = column("sec7_level_curve.csv", "value_Q31", 128)
    parts.append(emit("CV_LEVEL", lvl, 4, 124, True, "level 0..127 -> 0..1 (the modulation level curve)", 17))
    parts.append(emit("CV_OPATK", column("sec7_env_attack_step.csv", "attack_time_s(N/1500)"), 2, 124, True,
                      "operator envelope ATK 0..127 -> attack time, s (linear ramp)", 9))
    dec = column("sec7_env_decay_coef.csv", "time_to_-30dB_s")
    parts.append(emit("CV_OPDEC", dec, 2, 124, True,
                      "operator envelope DEC 0..127 -> time to -30 dB of the way to END, s (exponential)", 9))
    bw = column("sec7_basewidth_coef.csv", "fc_Hz_if_onepole=-ln(c)*48000/2pi", 509)
    parts.append(emit("CV_BWHZ", [min(bw[min(4 * i, 508)], 24000.0) for i in range(128)], 4, 124, True,
                      "base-width BASE / BASE+WIDTH 0..127 -> one-pole corner, Hz (127: the lowpass open)", 5))
    OUT.write_text("\n\n".join(parts) + "\n")
    print(f"-> {OUT}")


if __name__ == "__main__":
    main()
